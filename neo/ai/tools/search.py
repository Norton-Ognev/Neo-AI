# ai/tools/search.py
import re

# Все формы команды поиска: «найди», «найти», «найдите», «поищи», «ищи», «искать»…
_SEARCH_VERB = r"(?:найд(?:и|ите)(?:-ка)?|найти|поищи(?:те)?|поискать|ищи(?:те)?|искать)"
# Обращение и вежливые слова перед командой: «Привет, Нео, пожалуйста найди…»
_ADDRESSING = (
    r"(?:(?:привет\w*|здравствуй\w*|неос?|нева|нео|нелл?|пожалуйста|мне|"
    r"можешь|можете|ты)\b[\s,!.—-]*)*"
)
_SEARCH_COMMAND_RE = re.compile(
    rf"^\s*{_ADDRESSING}{_SEARCH_VERB}\b[\s,:—-]*(?P<rest>.*)$",
    re.IGNORECASE | re.DOTALL,
)

# Слова-«обёртки», которые не являются предметом поиска: «найди ЗАПИСЬ про ремонт»,
# «найди МЕРОПРИЯТИЕ день рождения» — в базе ищем «ремонт» и «день рождения».
_FILLER_WORDS = {
    "пожалуйста", "мне", "все", "всё", "там", "где", "когда", "что", "про",
    "о", "об", "обо", "информацию", "информация", "запись", "записи", "записях",
    "заметку", "заметки", "мероприятие", "мероприятия", "мероприятии",
    "событие", "события", "событии", "задачу", "задачи", "напоминание",
    "напоминания", "такое", "такой", "название", "я", "мой", "моя", "мои",
    "упоминался", "упоминалась", "упоминалось", "упоминается", "упоминал",
    "писал", "писала", "записывал", "записывала", "помнишь", "истории",
    "история", "старых", "старые",
    # «у меня», «у нас», «будет», «есть»… — связки вопроса «когда у меня встреча»
    "у", "меня", "нас", "есть", "будет", "бывает", "состоится", "проходит",
    "начинается", "запланирован", "запланирована", "запланировано",
    "назначен", "назначена", "назначено",
}


# Вопрос в форме просьбы напомнить: «Напомни, когда у меня встреча с Димой»,
# «Напомни, во сколько у меня прогулка», «Напомни какого числа у Олега день рождения».
# Это поиск, а не создание напоминания. Но «Напомни завтра в 10 позвонить Ивану» и
# «Напомни, что у меня завтра встреча» остаются обычными напоминаниями, поэтому:
#  • «во сколько / в какой день / какого числа / на какое время» — однозначно вопрос;
#  • «когда» считаем вопросом, только если дальше идёт «у меня / у Олега / будет / есть …»
#    (а не «напомни, когда приду домой, позвонить маме»).
_REMIND_QUESTION_RE = re.compile(
    rf"^\s*{_ADDRESSING}напомн(?:и|ите)(?:-ка)?(?:\s+мне)?[\s,:—-]*"
    r"(?:(?:во\s+сколько|в\s+какой\s+день|какого\s+числа|на\s+какое\s+(?:число|время))\b"
    r"|когда\b(?=[\s,]*(?:у\s+\w+|будет|состоится|начинается|проходит|был\w*|есть|"
    r"намечен\w*|запланирован\w*|назначен\w*)\b))"
    r"[\s,:—-]*(?P<rest>.*)$",
    re.IGNORECASE | re.DOTALL,
)


def parse_search_command(text: str) -> str | None:
    """Если фраза — команда поиска («Найти мероприятие X»), вернуть нормализованный
    запрос, иначе None. Разбор детерминированный: поиск не должен зависеть от того,
    что LLM решит про слова «мероприятие», «встреча», «прогулка» в запросе."""
    match = _SEARCH_COMMAND_RE.match(text or "") or _REMIND_QUESTION_RE.match(text or "")
    if not match:
        return None
    query = normalize_query(match.group("rest"))
    return query or None


def normalize_query(text: str) -> str:
    """
    Приводит поисковый запрос к нормальной форме.
    Удаляет мусорные фразы ассистента, лишние знаки препинания и пробелы.
    """
    if not text:
        return ""

    text_lower = text.lower().replace("ё", "е").strip()

    # Список стоп-слов и фраз, которые нужно вырезать из поискового запроса
    stop_phrases = [
        "посмотри где я писал про",
        "найди мне информацию о",
        "найди записи где упоминался",
        "посмотри в старых задачах",
        "найди задачу про",
        "ищи по ключевому слову",
        "найди где я записывал",
        "покажи записи про",
        "найди пожалуйста",
        "посмотри про",
        "найти",
        "найди",
        "ищи",
    ]

    # Удаляем мусорные фразы
    for phrase in stop_phrases:
        if text_lower.startswith(phrase):
            text_lower = text_lower.replace(phrase, "", 1).strip()
            break

    # Чистим от лишних символов в начале и конце (кавычки, точки, знаки вопроса)
    text_clean = re.sub(r'^[?.,!"\'\s]+|[?.,!"\'\s]+$', "", text_lower)

    # Убираем ведущие слова-обёртки, но не трогаем запрос из одного слова
    words = text_clean.split()
    while len(words) > 1 and words[0].strip(",.!?:;-—") in _FILLER_WORDS:
        words.pop(0)

    return " ".join(words).strip()